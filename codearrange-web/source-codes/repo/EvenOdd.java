// Description: Uses the modulo operator to determine if a number is even or odd.
// Cognitive Load Rating: 2

public class EvenOdd {
    public static void main(String[] args) {
        int number = 7;
        if (number % 2 == 0) {
            System.out.println("Even");
        } else {
            System.out.println("Odd");
        }
    }
}
