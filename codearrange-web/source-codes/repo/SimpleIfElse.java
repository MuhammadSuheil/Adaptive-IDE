// Description: Cek jika nilai besar dari atau sama dengan 50.
// Cognitive Load Rating: 2

public class SimpleIfElse {
    public static void main(String[] args) {
        int score = 85;
        if (score >= 50) {
            System.out.println("Pass");
        } else {
            System.out.println("Fail");
        }
    }
}
